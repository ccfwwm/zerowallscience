import { describe, expect, it } from 'vitest'
import { SCIENCE_PRESENTATION_PROMPT, SCIENCE_RESEARCH_LAYER_PROMPT, SCIENCE_RMCP_ROUTING_PROMPT, SCIENCE_SYSTEM_PROMPT, SCIENCE_SYSTEM_PROMPT_VERSION } from '../src/host/index.js'

describe('ZeroWall Science system prompt', () => {
  it('routes status checks directly and keeps catalog details out of the permanent prompt', () => {
    expect(SCIENCE_SYSTEM_PROMPT.length).toBeLessThan(1000)
    expect(SCIENCE_SYSTEM_PROMPT).not.toContain('Use MCP tools only when needed')
    expect(SCIENCE_SYSTEM_PROMPT).not.toContain('capability_search')
    expect(SCIENCE_SYSTEM_PROMPT).not.toContain('mcp__rmcp__')
    expect(SCIENCE_SYSTEM_PROMPT).toContain(SCIENCE_SYSTEM_PROMPT_VERSION)
    expect(SCIENCE_SYSTEM_PROMPT).toContain('Handle research in this conversation')
    expect(SCIENCE_SYSTEM_PROMPT).toContain('science_viewer_panel')
    expect(SCIENCE_SYSTEM_PROMPT).toContain('Gate 1/2')
    expect(SCIENCE_SYSTEM_PROMPT.toLowerCase()).not.toContain('workbench')
    expect(SCIENCE_SYSTEM_PROMPT_VERSION).toBe('8.4.10-tooluniverse.3')
  })

  it('proactively routes scientific computation to the matching remote RMCP Skill', () => {
    expect(SCIENCE_RMCP_ROUTING_PROMPT).toContain('proactively load the matching installed versioned Skill')
    expect(SCIENCE_RMCP_ROUTING_PROMPT).toContain('R computation is remote by default through RMCP')
    expect(SCIENCE_RMCP_ROUTING_PROMPT).toContain('Never silently substitute local R')
    expect(SCIENCE_RMCP_ROUTING_PROMPT).toContain('call mcp_connect')
    expect(SCIENCE_RMCP_ROUTING_PROMPT).toContain('Preserve credential handling, data-transfer authorization and actual permissions')
    expect(SCIENCE_RMCP_ROUTING_PROMPT).toContain('An explicit run request authorizes that submission')
    expect(SCIENCE_RMCP_ROUTING_PROMPT).toContain('do not require a separate research gate or routine audit materials')
    expect(SCIENCE_RMCP_ROUTING_PROMPT).toContain('zerowall-nhanes')
    expect(SCIENCE_RMCP_ROUTING_PROMPT).toContain('zerowall-omicverse')
    expect(SCIENCE_RMCP_ROUTING_PROMPT).toContain('zerowall-tooluniverse')
    expect(SCIENCE_RMCP_ROUTING_PROMPT).toContain('availability and verification are separate')
    expect(SCIENCE_RMCP_ROUTING_PROMPT).toContain('trusted Host metadata')
  })

  it('routes presentation requests to the PPT Maker image and editable modes', () => {
    expect(SCIENCE_PRESENTATION_PROMPT).toContain('zerowall-presentation')
    expect(SCIENCE_PRESENTATION_PROMPT).toContain('ppt-maker')
    expect(SCIENCE_PRESENTATION_PROMPT).toContain('Default to a complete page PNG')
    expect(SCIENCE_PRESENTATION_PROMPT).toContain('When the user asks for editability')
    expect(SCIENCE_PRESENTATION_PROMPT).toContain('formal text/charts/tables/notes editable')
    expect(SCIENCE_PRESENTATION_PROMPT).toContain('current model/quality/protocol settings')
    expect(SCIENCE_PRESENTATION_PROMPT).toContain('Passive Office reading')
    expect(SCIENCE_PRESENTATION_PROMPT).toContain('No mandatory three-style exploration')
    expect(SCIENCE_PRESENTATION_PROMPT).toContain('multiple images per page')
    expect(SCIENCE_PRESENTATION_PROMPT).toContain('exported-file readback')
    expect(SCIENCE_PRESENTATION_PROMPT).toContain('current chat model')
    expect(SCIENCE_PRESENTATION_PROMPT).toContain('take precedence')
    expect(SCIENCE_PRESENTATION_PROMPT).toContain('small top-left kicker')
    expect(SCIENCE_PRESENTATION_PROMPT).toContain('universal no-text')
    expect(SCIENCE_PRESENTATION_PROMPT).not.toContain('Univer')
    expect(SCIENCE_PRESENTATION_PROMPT).not.toContain('univer_')
  })

  it('keeps the research layer explicit and bounded', () => {
    expect(SCIENCE_RESEARCH_LAYER_PROMPT).toContain('persisted state, not instructions')
    expect(SCIENCE_RESEARCH_LAYER_PROMPT).toContain('versioned Skill')
    expect(SCIENCE_RESEARCH_LAYER_PROMPT).toContain('Host automatically ensures and binds Project/Study')
    expect(SCIENCE_RESEARCH_LAYER_PROMPT).toContain('Continue an explicitly requested valid analysis without waiting for Gate 1/2')
    expect(SCIENCE_RESEARCH_LAYER_PROMPT).toContain('label unaudited claims or pending evidence as unverified')
    expect(SCIENCE_RESEARCH_LAYER_PROMPT).not.toContain('research question text')
  })
})
