 it.each(['pause-first','automatic-first'])('keeps the current pause authoritative against %s automatic refresh and permits only explicit recovery',async order=>{
  const f=await fixture(),job=await f.ledger.prepare(f.scope,f.draft)
  await f.ledger.submitRequested(f.scope,job.id,job.revision);await settle(f)
  f.media.query.mockImplementationOnce(()=>new Promise(()=>{}))
  if(order==='pause-first')await Promise.all([f.ledger.pause(f.scope,job.id),f.ledger.refresh(f.scope,job.id,{background:true,automatic:true})])
  else await Promise.all([f.ledger.refresh(f.scope,job.id,{background:true,automatic:true}),f.ledger.pause(f.scope,job.id)])
  await settle(f)
  expect((await f.ledger.list(f.scope))[0]?.collection).toBe('paused')
  const before=f.media.query.mock.calls.length
  expect((await f.ledger.refresh(f.scope,job.id,{background:true,automatic:true})).collection).toBe('paused')
  await settle(f);expect(f.media.query).toHaveBeenCalledTimes(before)
  // The unused first response belongs to the pause-first case; explicit retry
  // must query the same original request rather than submit another generation.
  f.media.query.mockReset();f.media.query.mockResolvedValue({requestId:job.requestId,status:'completed',artifacts:[{key:'0',mediaType:'image/png'}]})
  const restored=await f.ledger.refresh(f.scope,job.id)
  expect(restored).toMatchObject({requestId:job.requestId,collection:'ready'})
  expect(f.media.query.mock.calls[0]?.[0]).toBe(job.requestId);expect(f.media.submit).toHaveBeenCalledOnce()
 })
 it('keeps partial original assets stoppable, skips saved bytes on retry and prevents automatic retry of failed downloads',async()=>{
  const f=await fixture(),job=await f.ledger.prepare(f.scope,f.draft)
  await f.ledger.submitRequested(f.scope,job.id,job.revision);await settle(f)
  f.media.query.mockResolvedValue({requestId:job.requestId,status:'completed',artifacts:[{key:'first',mediaType:'image/png'},{key:'second',mediaType:'image/png'}]})
  f.media.download.mockImplementationOnce(async()=>({bytes:Buffer.from('first'),mediaType:'image/png',sha256:createHash('sha256').update('first').digest('hex')})).mockImplementationOnce(()=>new Promise(()=>{}))
  await f.ledger.refresh(f.scope,job.id,{background:true,automatic:true})
  await vi.waitFor(async()=>expect((await f.ledger.list(f.scope))[0]).toMatchObject({collection:'downloading',assets:[expect.objectContaining({id:'first'})]}))
  expect((await f.ledger.pause(f.scope,job.id)).assets).toHaveLength(1)
  expect((await f.ledger.refresh(f.scope,job.id,{automatic:true,background:true})).collection).toBe('paused')
  f.media.download.mockRejectedValueOnce(new Error('MEDIA_DOWNLOAD_HTTP_401'))
  await expect(f.ledger.refresh(f.scope,job.id)).rejects.toThrow('401')
  const calls=f.media.download.mock.calls.length
  expect((await f.ledger.refresh(f.scope,job.id,{automatic:true,background:true})).collection).toBe('failed')
  expect(f.media.download).toHaveBeenCalledTimes(calls)
  const recovered=await f.ledger.refresh(f.scope,job.id)
  expect(recovered.collection).toBe('ready');expect(recovered.assets.map(a=>a.id)).toEqual(['first','second'])
  expect(f.media.download.mock.calls.filter(call=>call[1]==='first')).toHaveLength(1)
  expect(f.media.submit).toHaveBeenCalledOnce()
 })
 it.each(['query','download'])('adopts trusted history once while legacy %s never returns, pauses and resumes the exact original task without submitting',async phase=>{
  const f=await fixture(),history={requestId:'legacy-request-0001',taskId:'mt_original_legacy',selection:{...f.draft.selection,operation:'video'},status:'completed',artifacts:[{key:'video1',mediaType:'video/mp4'}]}
  f.media.list.mockResolvedValue([history]);f.media.query.mockResolvedValue(history)
  f.media.download.mockResolvedValue({bytes:Buffer.from('original-video'),mediaType:'video/mp4',sha256:createHash('sha256').update('original-video').digest('hex')})
  if(phase==='query')f.media.query.mockImplementationOnce(()=>new Promise(()=>{}))
  else f.media.download.mockImplementationOnce(()=>new Promise(()=>{}))
  const [first,duplicate]=await Promise.all([f.ledger.recover(f.scope,history.requestId),f.ledger.recover(f.scope,history.requestId)])
  expect(duplicate.id).toBe(first.id);expect(await f.ledger.list(f.scope)).toHaveLength(1)
  await vi.waitFor(()=>expect(phase==='query'?f.media.query:f.media.download).toHaveBeenCalled())
  const next=await f.ledger.prepare({...f.scope,sessionId:'new-session'},{kind:'video',prompt:'another session'})
  expect(next.sessionId).toBe('new-session')
  const paused=await f.ledger.pause(f.scope,first.id)
  expect(paused).toMatchObject({requestId:history.requestId,taskId:history.taskId,state:'completed',collection:'paused'})
  const restarted=new MediaJobLedger(f.media as any,async()=> 'account-a',f.root,{autoCollect:false})
  expect((await restarted.list(f.scope))[0]?.collection).toBe('paused')
  const restored=await restarted.refresh(f.scope,first.id)
  expect(restored).toMatchObject({id:first.id,requestId:history.requestId,taskId:history.taskId,collection:'ready'})
  expect(await readFile(join(f.cwd,restored.assets[0]!.path),'utf8')).toBe('original-video')
  await expect(restarted.prepare(f.scope,{kind:'video',prompt:'do not generate'},first.id)).rejects.toThrow('ALREADY_SUBMITTED')
  await restarted.submitRequested(f.scope,first.id,1)
  expect(f.media.submit).not.toHaveBeenCalled();expect(f.media.estimate).not.toHaveBeenCalled()
  expect(f.media.query.mock.calls.every(call=>call[0]===history.requestId)).toBe(true)
  expect(f.media.download.mock.calls.every(call=>call[0]===history.requestId&&call[1]==='video1')).toBe(true)
 })
