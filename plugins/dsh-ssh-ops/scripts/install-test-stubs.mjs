/**
 * Create minimal local stubs for the @deepseek-ai/* runtime packages so the
 * standalone `npm test` (node test/*.mjs) can load src/index.js without a full
 * DSH install. The stubs live under node_modules/ (gitignored) and are used
 * ONLY by the unit tests; the built lib/* keeps @deepseek-ai/* external
 * (see scripts/build-host.mjs), so real DSH runtime packages are still
 * resolved at plugin load time.
 *
 * Run once:  node scripts/install-test-stubs.mjs
 * Then:      npm test
 */
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const rootDir = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const base = resolve(rootDir, "node_modules/@deepseek-ai");

const stubs = {
  cordis: `export const Service = { init: Symbol("Service.init") };\n`,
  "dsh-credentials": `export function credentialRef(ref) { return ref; }\n`,
  "dsh-storage-domain": `export function defineDomain(spec) { return spec; }\nexport function domainTable(schema) { return schema; }\n`,
  "dsh-typert-protocol": `export class TypertRemoteService {}\n`,
  "dsh-tools": `export function defineTool(input) { return input; }\n`
};

for (const [name, indexJs] of Object.entries(stubs)) {
  const dir = resolve(base, name);
  mkdirSync(dir, { recursive: true });
  writeFileSync(resolve(dir, "package.json"), JSON.stringify({
    name: `@deepseek-ai/${name}`,
    version: "0.0.0-test-stub",
    type: "module",
    main: "index.js",
    exports: { ".": "./index.js" }
  }, null, 2) + "\n", "utf8");
  writeFileSync(resolve(dir, "index.js"), `// Test-only stub generated by scripts/install-test-stubs.mjs\n${indexJs}`, "utf8");
}
console.log(`install-test-stubs: wrote ${Object.keys(stubs).length} stubs under ${base}`);
