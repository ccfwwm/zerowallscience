import { execFileSync } from 'node:child_process'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
const root = resolve(import.meta.dirname, '../..')
const server = resolve(process.argv.find(arg => arg.startsWith('--server='))?.slice(9) ?? resolve(root, '../raiagentai'))
const json = execFileSync(process.execPath, ['--import', 'tsx', '--input-type=module', '-e', 'import {workflowCatalog} from "./gateway/src/tools.ts"; console.log(JSON.stringify(workflowCatalog({}),null,2))'], { cwd: server, encoding: 'utf8' }).trim()
const target = resolve(root, 'plugins/mcp/src/shared/r-workflows.ts')
const content = `// Generated by tools/integration/sync-r-workflows.mjs from raiagentai registrations.\nexport const rWorkflows = ${json} as const\n`
if (process.argv.includes('--check')) { if (await readFile(target, 'utf8') !== content) throw new Error('R workflow catalog drift; regenerate and review.'); console.log('R workflow catalog matches server registrations') }
else await writeFile(target, content)
