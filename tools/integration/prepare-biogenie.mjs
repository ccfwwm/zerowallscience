import { cp, lstat, mkdir, readFile, readdir, rename, symlink, unlink, writeFile } from 'node:fs/promises'
import { createHash, randomUUID } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { join, resolve, relative } from 'node:path'
import { contract } from '../build/paths.mjs'

const root = resolve(import.meta.dirname, '../..')
const source = join(root, 'resources/extensions/capabilities/biogenie')
const output = join(contract.dev, 'plugins/biogenie')
const target = join(output, `payload-${randomUUID()}`)
await mkdir(target, { recursive: true })
await cp(source, target, { recursive: true, filter: path => !relative(source, path).split(/[\\/]/u).some(part => ['__pycache__', '.git', '.venv', 'node_modules'].includes(part)) && !/\.py[co]$/u.test(path) })
execFileSync(process.env.ZEROWALL_BUILD_PYTHON ?? 'python', [join(root, 'tools/integration/generate-biogenie-catalog.py'), join(target, 'python'), join(target, 'operations.json')], { stdio: 'inherit', windowsHide: true })
const files = []
async function collect(directory) {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name)
    if (entry.isDirectory()) await collect(path)
    else if (entry.isFile() && entry.name !== 'payload-receipt.json') {
      const bytes = await readFile(path)
      files.push({ path: relative(target, path).replaceAll('\\', '/'), size: bytes.length, sha256: createHash('sha256').update(bytes).digest('hex') })
    } else if (!entry.isFile()) throw new Error('BioGenie payload contains an unsafe entry')
  }
}
await collect(target)
await writeFile(join(target, 'payload-receipt.json'), JSON.stringify({ schema: 1, files: files.sort((a,b) => a.path.localeCompare(b.path)) }, null, 2) + '\n')
// Source packages expose a compatibility link; generated bytes live in artifacts.
const link = join(root, 'plugins/biogenie/payload')
const previous = await lstat(link).catch(error => { if (error.code !== 'ENOENT') throw error })
if (previous?.isSymbolicLink()) await unlink(link)
else if (previous) {
  const receipt = JSON.parse(await readFile(join(link, 'payload-receipt.json'), 'utf8'))
  if (receipt.schema !== 1 || !Array.isArray(receipt.files)) throw new Error('Refusing to replace an unowned BioGenie payload directory')
  // Preserve the earlier generated directory, including any extra local files.
  await rename(link, join(output, `previous-payload-${randomUUID()}`))
}
await symlink(target, link, process.platform === 'win32' ? 'junction' : 'dir')
