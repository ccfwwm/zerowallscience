/** Refresh model capacity metadata; gateway-provided limits retain priority. */
import { createHash } from 'node:crypto'
import { readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'
import { pathToFileURL } from 'node:url'

/** Prefer the model author's direct listing; otherwise retain conservative limits across providers. */
export function capacities(catalog) {
  const result = {}
  const positive = value => Number.isSafeInteger(value) && value > 0
  for (const provider of Object.values(catalog)) {
    for (const [id, model] of Object.entries(provider.models ?? {})) {
      const context = model.limit?.context
      const output = model.limit?.output
      if (!positive(context)) continue
      const previous = result[id]
      result[id] = { context: Math.min(previous?.context ?? context, context),
        ...(positive(output) ? { output: Math.min(previous?.output ?? output, output) } : previous?.output ? { output: previous.output } : {}) }
    }
  }
  for (const providerId of ['anthropic', 'openai', 'google', 'deepseek', 'xai', 'mistral', 'cohere', 'moonshotai', 'zai', 'minimax', 'alibaba']) {
    for (const [id, model] of Object.entries(catalog[providerId]?.models ?? {})) {
      if (positive(model.limit?.context)) result[id] = { context: model.limit.context, ...(positive(model.limit.output) ? { output: model.limit.output } : {}) }
    }
  }
  if (Object.keys(result).length === 0) throw new Error('models.dev returned no model capacities.')
  return Object.fromEntries(Object.entries(result).sort(([a], [b]) => a < b ? -1 : a > b ? 1 : 0))
}

/** Read an optional saved response or fetch the source, then replace the generated reference. */
export async function main() {
  const bytes = process.argv[2] ? await readFile(resolve(process.argv[2])) : await (async () => {
    const response = await fetch('https://models.dev/api.json', { signal: AbortSignal.timeout(60_000), redirect: 'error' })
    if (!response.ok) throw new Error(`models.dev HTTP ${response.status}`)
    return Buffer.from(await response.arrayBuffer())
  })()
  const metadata = capacities(JSON.parse(bytes.toString('utf8')))
  const source = '/** Generated by scripts/update-models-dev.mjs; gateway metadata takes priority. */\n'
    + 'export const MODELS_DEV_SOURCE = "https://models.dev/api.json" as const\n'
    + `export const MODELS_DEV_FETCHED_AT = ${JSON.stringify(new Date().toISOString())} as const\n`
    + `export const MODELS_DEV_SHA256 = ${JSON.stringify(createHash('sha256').update(bytes).digest('hex'))} as const\n`
    + `export const MODELS_DEV_CONTEXT: Readonly<Record<string, { context: number; output?: number }>> = ${JSON.stringify(metadata, null, 2)}\n`
  await writeFile(new URL('../src/account/host/models-dev-context.ts', import.meta.url), source)
  console.log(`Updated ${Object.keys(metadata).length} model ids from models.dev.`)
}

if (process.argv[1] && import.meta.url === pathToFileURL(resolve(process.argv[1])).href) await main()
